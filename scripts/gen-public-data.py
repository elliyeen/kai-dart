#!/usr/bin/env python3
"""Generate src/lib/stations/publicData.generated.ts from docs/data/official-reconciliation.json
(official DART GTFS match per original station record). Re-run after refreshing the reconciliation."""
import json
d = json.load(open("docs/data/official-reconciliation.json"))
src = d["sources"]
rec = {}
for r in d["records"]:
    m = r.get("matchedOfficialStop")
    if not m: continue
    rec[r["id"]] = {"stopId": m["stopId"], "officialName": m["name"].title().replace(" Station", ""), "officialLines": m["officialLines"], "lineConfirmed": bool(r["lineMembershipConfirmed"]), **({"note": r["note"]} if r.get("note") and r["note"] != "ok" else {})}
out = (
"// GENERATED by scripts/gen-public-data.py from docs/data/official-reconciliation.json — do not edit by hand.\n"
"// Official DART public GTFS schedule data matched to each original station record. This is PUBLIC SCHEDULE data,\n"
"// not live condition, inspection or asset data.\n"
"export interface PublicStop { stopId: string; officialName: string; officialLines: string[]; lineConfirmed: boolean; note?: string }\n"
"export const PUBLIC_SOURCE = " + json.dumps({"name": "DART GTFS (public schedule data)", "url": src["gtfsUrl"], "feedVersion": src["feedVersion"], "effective": f'{src["feedStart"]} to {src["feedEnd"]}', "retrieved": "2026-10-31"}, indent=2) + " as const;\n"
"export const PUBLIC_STOPS: Record<string, PublicStop> = " + json.dumps(rec, indent=1) + ";\n")
open("src/lib/stations/publicData.generated.ts", "w").write(out)
print(len(rec), "records")
