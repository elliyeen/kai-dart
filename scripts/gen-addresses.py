#!/usr/bin/env python3
"""Generate src/lib/stations/addresses.generated.ts from docs/data/station-addresses.json
(addresses as published on each station's DART page; county from OSM reverse geocode; see the .md for discrepancies)."""
import json
d = json.load(open("docs/data/station-addresses.json"))["stations"]
out = {}
for name, v in d.items():
    e = {"street": v["street"], "city": v["city"], "state": v.get("state", "TX"), "zip": v["zip"], "county": v.get("county"), "stopId": v["gtfsStopId"], "source": v["source"]}
    if v.get("additionalStops"):
        e["additional"] = [{"stopId": a["gtfsStopId"], "name": a["officialName"].title(), "address": a["dartPublishedAddress"], "source": a["source"]} for a in v["additionalStops"]]
    out[name] = e
open("src/lib/stations/addresses.generated.ts", "w").write(
"// GENERATED by scripts/gen-addresses.py from docs/data/station-addresses.json — do not edit by hand.\n"
"// Street addresses as published on each station's DART page; county from an OpenStreetMap reverse geocode of the official coordinates.\n"
"export interface StationAddress { street: string; city: string; state: string; zip: string; county: string | null; stopId: string; source: string; additional?: { stopId: string; name: string; address: string; source: string }[] }\n"
"export const STATION_ADDRESSES: Record<string, StationAddress> = " + json.dumps(out, indent=1) + ";\n")
print(len(out))
