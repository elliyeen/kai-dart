#!/usr/bin/env python3
"""Generate src/lib/geo/dfw-counties.ts from the US Census cartographic boundary shapefile
(cb_2023_us_county_500k, public domain). Usage: gen-dfw-geo.py <path/to/cb_2023_us_county_500k> (no extension).
Pure-stdlib shapefile/DBF reader; the input is treated as untrusted data (parsed, never executed)."""
import json, struct, sys
base = sys.argv[1]
WANT = {'48113':'Dallas','48085':'Collin','48121':'Denton','48439':'Tarrant','48397':'Rockwall','48257':'Kaufman','48251':'Johnson','48139':'Ellis','48367':'Parker','48497':'Wise','48231':'Hunt','48147':'Fannin','48181':'Grayson'}

# --- DBF: GEOID per record, in file order
dbf = open(base + ".dbf", "rb").read()
nrec, hlen, rlen = struct.unpack("<IHH", dbf[4:12])
fields, off, pos = [], 1, 32
while dbf[pos] != 0x0D:
    name = dbf[pos:pos+11].split(b"\0")[0].decode(); ln = dbf[pos+16]
    fields.append((name, off, ln)); off += ln; pos += 32
fo = next((o, l) for n, o, l in fields if n == "GEOID")
geoids = [dbf[hlen + i*rlen + fo[0]: hlen + i*rlen + fo[0] + fo[1]].decode().strip() for i in range(nrec)]

# --- SHP: polygon records in the same order
shp = open(base + ".shp", "rb").read()
def ring_area(r): return sum((r[i][0]*r[i+1][1] - r[i+1][0]*r[i][1]) for i in range(len(r)-1)) / 2
out, pos, idx = [], 100, 0
while pos < len(shp):
    _, clen = struct.unpack(">ii", shp[pos:pos+8]); body = shp[pos+8: pos+8+clen*2]; pos += 8 + clen*2
    gid = geoids[idx]; idx += 1
    if gid not in WANT: continue
    st, = struct.unpack("<i", body[:4])
    if st != 5: continue
    nparts, npts = struct.unpack("<ii", body[36:44])
    parts = list(struct.unpack(f"<{nparts}i", body[44:44+4*nparts]))
    pts = [struct.unpack("<dd", body[44+4*nparts+16*i: 44+4*nparts+16*i+16]) for i in range(npts)]
    rings = []
    for p in range(nparts):
        ring = pts[parts[p]: parts[p+1] if p+1 < nparts else npts]
        if ring_area(ring) < 0:  # clockwise = outer ring in ESRI shapefiles
            thin = []
            for lng, lat in ring:
                q = [round(lng, 3), round(lat, 3)]
                if not thin or thin[-1] != q: thin.append(q)
            if len(thin) >= 4: rings.append(thin)
    out.append({"fips": gid, "name": WANT[gid], "rings": rings})
out.sort(key=lambda r: r["fips"])
open("src/lib/geo/dfw-counties.ts", "w").write(
"// GENERATED by scripts/gen-dfw-geo.py — do not edit by hand.\n"
"// County outlines from US Census cartographic boundaries (cb_2023_us_county_500k, public domain), simplified to 3 decimals.\n"
"// Base-map context only: not survey-grade and not a DART service-area boundary.\n"
"export interface CountyShape { fips: string; name: string; rings: [number, number][][] } // rings of [lng, lat]\n"
"export const DFW_COUNTIES: CountyShape[] = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(out), "counties,", sum(len(r) for c in out for r in c["rings"]), "points")
