#!/usr/bin/env python3
"""Generate src/lib/stations/records.generated.ts from docs/baseline/stations-baseline.json.
The baseline JSON is the immutable snapshot of the ORIGINAL app; this file is the canonical
runtime copy. Parity tests assert they stay identical."""
import json
b=json.load(open("docs/baseline/stations-baseline.json"))["records"]
lines=[]
for r in b:
    lines.append("  "+json.dumps({"id":r["id"],"name":r["name"],"lineId":r["lineId"],"city":r["city"],"lat":r["lat"],"lng":r["lng"],
      **({"closure":r["closure"]} if r["closure"] else {}),
      "demo":{"score":r["demoScore"],"status":r["demoStatus"],"issues":r["demoIssues"]}},ensure_ascii=False)+",")
open("src/lib/stations/records.generated.ts","w").write(
"// GENERATED by scripts/gen-station-data.py from docs/baseline/stations-baseline.json — do not edit by hand.\n"
"// One record per ORIGINAL station id / line membership. `demo` values are SYNTHETIC DEMO data, not DART facts.\n"
'import type { StationRecord } from "./types";\n\n'
"export const STATION_RECORDS: StationRecord[] = [\n"+"\n".join(lines)+"\n];\n")
print(len(lines))
